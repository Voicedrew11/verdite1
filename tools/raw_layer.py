@dataclasses.dataclass
class Skipped:
    constants: int = 0
    names: list = dataclasses.field(default_factory=list)


def _builtin(text):
    if text == "bool":
        return Ty("bool")
    if text == "char":
        return Ty("char", bits=8, signed=True)
    if text in INTEGER_TYPES:
        bits, signed = INTEGER_TYPES[text]
        return Ty("integer", bits=bits, signed=signed)
    if text in FLOAT_TYPES:
        return Ty("number", bits=FLOAT_TYPES[text])
    return None


def _normalize(text):
    result = " ".join(text.split())
    previous = None
    while result != previous:
        previous = result
        result = re.sub(r"^(const|volatile) ", "", result)
        result = re.sub(r" (const|volatile)$", "", result)
    return result


def _split_args(text):
    args, depth, current = [], 0, ""
    for char in text:
        if char in "<([":
            depth += 1
        elif char in ">)]":
            depth -= 1
        if char == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += char
    if current.strip():
        args.append(current.strip())
    return args


def _held(category, detail):
    return Ty("held", held=Held(category, detail))


class Layer:
    """Describes the reachable declarations and checks the listed file against them."""

    def __init__(self, index, listed, include_dir):
        self.index = index
        self.listed = listed
        self.include_dir = include_dir
        self.field_limits = {}
        self.global_limits = {}
        self.records = {}
        self.enums = {}
        self.busy = set()
        self.enum_storage_used = False
        self._check_listed()

    # Parsing

    def parse_type(self, text, depth=0):
        if depth > 16:
            return _held("unsupported", text)
        t = _normalize(text)
        if not t:
            return _held("unknown-type", "no type")
        if "(anonymous" in t or "(unnamed" in t:
            return _held("anonymous", t)
        if "(" in t:
            return _held("function", t)
        if t.endswith("&"):
            return _held("reference", t)
        if t.endswith("*"):
            return _held("pointer", t)
        if t.endswith("]"):
            return self._c_array(t, depth)
        if t.startswith("std::array<") and t.endswith(">"):
            return self._std_array(t, depth)
        if t.startswith(ENUM_WRAPPER + "<") and t.endswith(">"):
            return self._enum_storage(t, depth)
        if t.startswith("std::"):
            return _held("std-type", t)
        t = re.sub(r"^(struct|class|union|enum) ", "", t)
        return _builtin(t) or self._named(t, depth)

    def _c_array(self, text, depth):
        match = re.match(r"^(.*?)\[(\d+)\](.*)$", text)
        if match is None:
            return _held("array-size", text)
        element = self.parse_type(match.group(1) + match.group(3), depth + 1)
        return self._array_of(element, int(match.group(2)))

    def _std_array(self, text, depth):
        args = _split_args(text[len("std::array<"):-1])
        if len(args) != 2 or not args[1].isdigit():
            return _held("array-size", text)
        return self._array_of(self.parse_type(args[0], depth + 1), int(args[1]))

    @staticmethod
    def _array_of(element, length):
        if element.kind == "held":
            return element
        if element.kind == "char":
            return Ty("string", length=length)
        return Ty("array", element=element, length=length)

    def _enum_storage(self, text, depth):
        args = _split_args(text[len(ENUM_WRAPPER) + 1:-1])
        if len(args) != 2:
            return _held("unsupported", text)
        enum_ty = self.parse_type(args[0], depth + 1)
        storage = self.parse_type(args[1], depth + 1)
        if enum_ty.kind != "enum":
            return _held("unknown-type", f"{args[0]} is not an enum")
        if storage.kind not in ("integer", "char"):
            return _held("unsupported", f"{ENUM_WRAPPER} storage {args[1]}")
        return Ty("enum_storage", ref=enum_ty.ref, bits=storage.bits, signed=storage.signed)

    def _named(self, name, depth):
        rid = self.index.record_names.get(name)
        if rid is not None:
            return Ty("record", ref=self.index.complete_id(rid, self.index.records, self.index.record_names))
        eid = self.index.enum_names.get(name)
        if eid is not None:
            return Ty("enum", ref=self.index.complete_id(eid, self.index.enums, self.index.enum_names))
        tid = self.index.typedef_names.get(name)
        if tid is not None:
            return self._typedef(tid, depth)
        if "<" in name:
            return _held("unsupported", f"{name} is a template instance the generator does not describe")
        return _held("unknown-type", f"{name} is not declared in the decomp's headers")

    def _typedef(self, tid, depth):
        typedef = self.index.typedefs[tid]
        if typedef.decl_id:
            if typedef.decl_id in self.index.records:
                return Ty("record", ref=self.index.complete_id(
                    typedef.decl_id, self.index.records, self.index.record_names))
            if typedef.decl_id in self.index.enums:
                return Ty("enum", ref=self.index.complete_id(
                    typedef.decl_id, self.index.enums, self.index.enum_names))
            if typedef.decl_id in self.index.typedefs:
                return self._typedef(typedef.decl_id, depth + 1)
        return self.parse_type(typedef.type_text, depth + 1)

    def _find_member(self, rid, name, in_union=False):
        """(member, inside a union) for the named member, through unnamed structs and unions."""
        rec = self.index.records.get(rid)
        if rec is None:
            return None
        for member in rec.members:
            if member.name == name:
                return member, in_union or rec.union
        for member in rec.members:
            if not member.name and member.anon_id:
                found = self._find_member(member.anon_id, name, in_union or rec.union)
                if found is not None:
                    return found
        return None

    def _member_names(self, rid):
        rec = self.index.records.get(rid)
        if rec is None:
            return []
        names = []
        for member in rec.members:
            if member.name:
                names.append(member.name)
            elif member.anon_id:
                names.extend(self._member_names(member.anon_id))
        return names

    # The listed file

    def _check_listed(self):
        for name in self.listed.instances:
            self._check_instance(name)
        for key, entry in self.listed.fields.items():
            self._check_field(key, entry)
        for name, entry in self.listed.globals.items():
            self._check_global(name, entry)
        for name in sorted(self.listed.flags):
            if name not in self.index.enum_names:
                raise ConfigError(f"[enums.{name}]: no enum named {name}")
        for key in sorted(self.listed.union_expose):
            self._check_union(key)
        for key in sorted(self.listed.held_back):
            self._check_held_back(key)
        self._check_alias_collisions()

    def _check_instance(self, name):
        rid = self.index.record_names.get(name)
        if rid is None or not self.index.records[rid].complete:
            raise ConfigError(f"[templates] instances: {name} is not a class template instance in the headers")

    def _owner_record(self, key, where):
        owner, _, member = key.rpartition(".")
        rid = self.index.record_names.get(owner)
        if not owner or rid is None:
            raise ConfigError(f"{where}: no struct named {owner or key}")
        found = self._find_member(rid, member)
        if found is None:
            raise ConfigError(f"{where}: {owner} has no field {member}")
        return found

    def _check_field(self, key, entry):
        where = f"[fields.\"{key}\"]"
        member, _ = self._owner_record(key, where)
        ty = self.parse_type(member.type_text)
        self.field_limits[key] = self._limits(entry, ty, where)

    def _check_global(self, name, entry):
        where = f"[globals.{name}]"
        var = self.index.variable_names.get(name)
        if var is None:
            raise ConfigError(f"{where}: no global named {name}")
        self.global_limits[name] = self._limits(entry, self.parse_type(var.type_text), where)

    def _check_union(self, key):
        where = f"[unions] expose \"{key}\""
        _, in_union = self._owner_record(key, where)
        if not in_union:
            raise ConfigError(f"{where}: {key} is not a union member")

    def _check_held_back(self, key):
        if key in self.index.variable_names or key in self.index.record_names:
            return
        if key in self.index.enum_names or key in self.index.typedef_names:
            return
        if "." in key:
            self._owner_record(key, f"[held_back] {key}")
            return
        raise ConfigError(f"[held_back] {key}: no global, field or type named {key}")

    def _check_alias_collisions(self):
        owners = {}
        for key, entry in self.listed.fields.items():
            if entry.alias:
                owners.setdefault(key.rpartition(".")[0], {})[key.rpartition(".")[2]] = entry.alias
        for owner, renames in owners.items():
            rid = self.index.record_names[owner]
            final = [renames.get(name, name) for name in self._member_names(rid)]
            self._reject_duplicates(final, f"struct {owner}")
        emitted = {}
        for var in self.index.variables:
            if var.name and not self._is_constant(var):
                emitted.setdefault(var.name, var.short)
        final_globals = []
        for name, short in sorted(emitted.items()):
            entry = self.listed.globals.get(name)
            final_globals.append(entry.alias if entry and entry.alias else short)
        self._reject_duplicates(final_globals, "the globals")

    @staticmethod
    def _reject_duplicates(names, where):
        seen = set()
        for name in names:
            if name in seen:
                raise ConfigError(f"{where}: two fields are called {name} (an alias collides)")
            seen.add(name)

    def _limits(self, entry, ty, where):
        rng = None
        if entry.range is not None:
            rng = self._resolve_range(entry.range, ty, where)
        return Limits(range=rng, read_only=entry.read_only, doc=entry.why, alias=entry.alias)

    def _resolve_range(self, spec, ty, where):
        leaf = ty
        while leaf.kind == "array":
            leaf = leaf.element
        bits, signed = self._storage_of(leaf, where)
        if isinstance(spec, str):
            array = self._global_type(spec)
            if array is None or array.kind != "array":
                raise ConfigError(f"{where}: range = \"{spec}\" needs a global array of that name")
            low, high = 0, array.length - 1
        else:
            low, high = spec
        if low > high:
            raise ConfigError(f"{where}: range min {low} is above max {high}")
        bottom, top = _storage_bounds(bits, signed)
        if low < bottom or high > top:
            kind = "signed" if signed else "unsigned"
            raise ConfigError(
                f"{where}: range {low}..{high} is wider than its storage "
                f"({kind} {bits}-bit: {bottom}..{top})")
        return (low, high)

    def _storage_of(self, ty, where):
        if ty.kind in ("integer", "char", "enum_storage"):
            return ty.bits, ty.signed
        if ty.kind == "enum":
            return self._enum_underlying(ty.ref)
        if ty.kind == "held":
            raise ConfigError(f"{where}: the generator holds this back ({ty.held.detail}), so it takes no range")
        raise ConfigError(f"{where}: a range needs an integer or an enum, not {ty.kind}")

    def _global_type(self, name):
        var = self.index.variable_names.get(name)
        return None if var is None else self.parse_type(var.type_text)

    def _enum_underlying(self, eid):
        enum = self.index.enums[eid]
        if enum.fixed:
            ty = self.parse_type(enum.fixed)
            if ty.kind not in ("integer", "char"):
                raise ConfigError(f"enum {enum.tag or eid}: unknown underlying type {enum.fixed}")
            return ty.bits, ty.signed
        values = [value for _, value in enum.values] or [0]
        low, high = min(values), max(values)
        if low < 0:
            return (32, True) if low >= -2**31 and high < 2**31 else (64, True)
        return (32, False) if high < 2**32 else (64, False)

    # Describing

    def record(self, rid):
        if rid in self.records:
            return self.records[rid]
        if rid in self.busy:
            return Held("recursive", f"{rid} contains itself")
        self.busy.add(rid)
        try:
            result = self._describe_record(rid)
        finally:
            self.busy.discard(rid)
        self.records[rid] = result
        return result

    def _describe_record(self, rid):
        rec = self.index.records[rid]
        spelled, typedef_file = self.index.spelled(rid)
        if not rec.complete:
            return Held("incomplete", f"{spelled or 'an unnamed struct'} is incomplete")
        if rec.bases:
            return Held("base-class", f"{spelled} has a base class")
        if not spelled:
            return Held("anonymous", "an unnamed struct or union is not named by any type")
        if spelled in self.listed.held_back:
            return Held("listed", f"{spelled}: {self.listed.held_back[spelled]}")
        if any(m.name and m.access in NONPUBLIC_ACCESS for m in rec.members):
            return Held("private-data", f"{spelled} has private data")
        items = []
        for member in rec.members:
            items.extend(self._member_items(member, spelled, rec.union))
        fields = [item for item in items if isinstance(item, FieldEmit)]
        held = [item for item in items if isinstance(item, Held)]
        if not fields:
            return Held("no-fields", f"{spelled} has no exposed fields")
        files = {rec.file} | ({typedef_file} if typedef_file else set())
        return RecordEmit(id=rid, spelled=spelled, fields=fields, held=held, files=files)

    def _member_items(self, member, owner, in_union):
        if member.name:
            return [self._field(member, owner, in_union)]
        anon = self.index.records.get(member.anon_id)
        if anon is None:
            return [Held("anonymous", f"{owner}: an unnamed member the generator cannot read")]
        items = []
        for sub in anon.members:
            items.extend(self._member_items(sub, owner, in_union or anon.union))
        return items

    def _field(self, member, owner, in_union):
        key = f"{owner}.{member.name}"
        if member.bitfield:
            return Held("bitfield", f"{key} is a bitfield")
        if in_union and key not in self.listed.union_expose:
            return Held("union-member", f"{key}: a union member the listed file does not expose")
        if key in self.listed.held_back:
            return Held("listed", f"{key}: {self.listed.held_back[key]}")
        ty = self.parse_type(member.type_text)
        reason = self._ensure(ty)
        if reason is not None:
            return Held(reason.category, f"{key}: {reason.detail}")
        limits = self.field_limits.get(key, Limits())
        return FieldEmit(member.name, limits.alias or member.name, key, ty, limits)

    def _ensure(self, ty):
        """Describes what ty reaches; the Held that stops it, or None."""
        if ty.kind == "held":
            return ty.held
        if ty.kind == "array":
            return self._ensure(ty.element)
        if ty.kind in ("enum", "enum_storage"):
            emitted = self.enum(ty.ref)
            return emitted if isinstance(emitted, Held) else None
        if ty.kind == "record":
            emitted = self.record(ty.ref)
            return emitted if isinstance(emitted, Held) else None
        return None

    def enum(self, eid):
        if eid in self.enums:
            return self.enums[eid]
        enum = self.index.enums[eid]
        spelled, typedef_file = self.index.spelled(eid)
        if not enum.complete:
            result = Held("incomplete", f"{spelled or 'an unnamed enum'} is incomplete")
        elif not spelled:
            result = Held("anonymous", "an unnamed enum is not named by any type")
        elif spelled in self.listed.held_back:
            result = Held("listed", f"{spelled}: {self.listed.held_back[spelled]}")
        else:
            result = EnumEmit(
                id=eid,
                spelled=spelled,
                values=enum.values,
                flags=spelled in self.listed.flags,
                files={enum.file} | ({typedef_file} if typedef_file else set()),
            )
        self.enums[eid] = result
        return result

    def describe_globals(self):
        """(globals exposed, globals held back as (name, Held), what was skipped)."""
        exposed, held, skipped = [], [], Skipped()
        seen = set()
        for var in sorted(self.index.variables, key=lambda v: (v.file, v.line)):
            if not var.name or var.name in seen:
                continue
            seen.add(var.name)
            if self._is_constant(var):
                skipped.constants += 1
                skipped.names.append(var.name)
                continue
            emitted = self._global(var)
            if isinstance(emitted, Held):
                held.append((var, emitted))
            else:
                exposed.append(emitted)
        return exposed, held, skipped

    @staticmethod
    def _is_constant(var):
        if var.internal or var.storage == "static" or var.constexpr:
            return True
        return var.type_text.startswith("const ") and var.storage != "extern" and not var.inline

    def _global(self, var):
        if var.name in self.listed.held_back:
            return Held("listed", f"{var.name}: {self.listed.held_back[var.name]}")
        ty = self.parse_type(var.type_text)
        reason = self._ensure(ty)
        if reason is not None:
            return Held(reason.category, f"{var.name}: {reason.detail}")
        limits = self.global_limits.get(var.name, Limits())
        lua_name = limits.alias or var.short
        if lua_name in FORBIDDEN_LUA_NAMES:
            raise ConfigError(f"global {var.name}: the Lua name {lua_name} is taken by the layer")
        return GlobalEmit(var.name, lua_name, ty, var.file, limits)


def _storage_bounds(bits, signed):
    if signed:
        return -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    return 0, (1 << bits) - 1


