#!/usr/bin/env python3
"""Hold the modding API's stable names to docs/api_surface.txt (docs/MODDING.md, "Stability").

Boots the game to have it write its definitions file, and compares every name in it, apart from kf.raw, kf.call
and kf.hook, which promise nothing. A name gone from the game breaks mods and needs a new major version; a new
one needs --write, to take it into the file, and a new minor version.
Usage: tools/api_surface.py BINARY [--data data/en] [--write]
"""

import argparse
import json
import os
import re
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SURFACE = ROOT / "docs" / "api_surface.txt"
PORT = 27913  # not smoke.py's or the game's
TIMEOUT = 60
UNSTABLE = ("kf.raw", "kf.call", "kf.hook")


def is_unstable(table):
    return any(table == root or table.startswith(root + ".") for root in UNSTABLE)


def stable_names(definitions):
    """Each name: a global, a callback or event, or table.field. Generated by the game, so the form is fixed."""
    names = set()
    table = None
    for line in definitions.splitlines():
        if match := re.match(r"---@class (\S+)", line):
            table = match[1]
            if not is_unstable(table):
                names.add(table)
        elif match := re.match(r"---@field (\S+)", line):
            if table and not is_unstable(table):
                names.add(f"{table}.{match[1]}")
        elif match := re.match(r"(\w+) = (nil|\{\})$", line):
            names.add(match[1])
            table = None
    return names


def game_definitions(binary, data):
    """The definitions file a fresh user folder gets."""
    with tempfile.TemporaryDirectory() as home:
        saves = Path(home) / "saves"
        saves.mkdir()
        env = dict(os.environ, KF_SHELL=str(PORT), XDG_DATA_HOME=home)
        game = subprocess.Popen([binary, "--data", data, "--saves", str(saves), "--headless", "--turbo", "--skip-intro"],
                                env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            deadline = time.monotonic() + TIMEOUT
            while True:
                try:
                    with socket.create_connection(("127.0.0.1", PORT), timeout=10) as channel:
                        channel.sendall(b"quit\n")
                    break
                except OSError:
                    if time.monotonic() > deadline or game.poll() is not None:
                        sys.exit("api surface: the game did not open its command channel")
                    time.sleep(0.2)
            if game.wait(timeout=TIMEOUT) != 0:
                sys.exit(f"api surface: the game exited with {game.returncode}")
        finally:
            if game.poll() is None:
                game.kill()
                game.wait()
        return (Path(home) / "Verdite" / "Verdite1" / "mods" / "kf.d.lua").read_text()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("binary")
    parser.add_argument("--data", default=str(ROOT / "data/en"))
    parser.add_argument("--write", action="store_true", help="take the game's names into the file")
    args = parser.parse_args()

    names = stable_names(game_definitions(str(Path(args.binary).resolve()), args.data))
    if args.write:
        SURFACE.write_text("# The modding API's stable names, checked by tools/api_surface.py; written by its --write.\n" +
                           "\n".join(sorted(names)) + "\n")
        print(f"api surface: wrote {len(names)} names")
        return
    held = {line for line in SURFACE.read_text().splitlines() if line and not line.startswith("#")}
    gone, added = sorted(held - names), sorted(names - held)
    for name in gone:
        print(f"gone from the game: {name} (breaks mods: it needs a new major version, or put it back)")
    for name in added:
        print(f"new in the game: {name} (raise the minor version, and run tools/api_surface.py --write)")
    if gone or added:
        sys.exit("api surface: the game's names differ from docs/api_surface.txt")
    print(f"api surface: {len(names)} names as held")


if __name__ == "__main__":
    main()
